// Run with playwright-cli run-code --filename in an isolated session. Guest data only.
async (page) => {
  page.setDefaultTimeout(5000)
  await page.setViewportSize({ width: 1280, height: 900 })
  await page.goto('http://localhost:3001')
  await page.getByRole('button', { name: 'Entra come ospite (senza salvataggio dati)', exact: true }).click()
  await page.getByRole('button', { name: 'Debiti/Crediti', exact: true }).click()
  const form = page.locator('app-debt-credit')
  const person = form.getByRole('textbox', { name: 'Persona/Motivo', exact: true })
  const amount = form.getByRole('textbox', { name: 'Importo (€)', exact: true })
  const checkBalance = async text => {
    await page.waitForFunction(text => document.querySelector('app-debt-credit .balance')?.textContent.trim() === text, text)
  }
  await checkBalance('0,00 €')
  if (await form.getByRole('textbox').count() !== 2) throw new Error('Expected only Persona/Motivo and amount')
  if (await form.getByText('Usa il segno meno per un debito.', { exact: false }).count()) throw new Error('Obsolete help text remains')
  await person.fill('Credito di prova')
  await amount.fill('+-15000')
  if (await form.getByRole('button', { name: 'Aggiungi', exact: true }).isEnabled()) throw new Error('Malformed sign accepted')
  await amount.fill('+15000')
  await form.getByRole('button', { name: 'Aggiungi', exact: true }).click()
  await checkBalance('+15.000,00 €')
  await form.getByRole('button', { name: 'Elimina voce di Credito di prova', exact: true }).click()
  await checkBalance('0,00 €')
  for (const [name, value, why] of [['Anna', '+125,50', 'Cena'], ['Luca', '-25.20', 'Regalo'], ['Anna', '-0,10', 'Conguaglio']]) {
    await person.fill(name + ' · ' + why)
    await amount.fill(value)
    await form.getByRole('button', { name: 'Aggiungi', exact: true }).click()
    await page.waitForFunction(() => document.querySelector('#debt-person').value === '')
  }
  await checkBalance('+100,20 €')
  await page.context().grantPermissions(['clipboard-read', 'clipboard-write'])
  await form.getByRole('button', { name: 'Copia saldo', exact: true }).click()
  if (await page.evaluate(() => navigator.clipboard.readText()) !== '+100,20') throw new Error('Copy lost signed cents')
  await form.getByRole('button', { name: 'Modifica voce di Luca · Regalo', exact: true }).click()
  await page.waitForFunction(() => document.querySelector('#debt-amount').value === '-25,20')
  await amount.fill('-225,20')
  await form.getByRole('button', { name: 'Salva', exact: true }).click()
  await checkBalance('-99,80 €')
  await form.getByRole('button', { name: 'Copia saldo', exact: true }).click()
  if (await page.evaluate(() => navigator.clipboard.readText()) !== '-99,80') throw new Error('Wrong negative clipboard')
  await form.getByRole('button', { name: 'Modifica voce di Luca · Regalo', exact: true }).click()
  await page.waitForFunction(() => document.querySelector('#debt-amount').value === '-225,20')
  await amount.fill('2,345')
  if (await form.getByRole('button', { name: 'Salva', exact: true }).isEnabled()) throw new Error('Invalid decimals accepted')
  await form.getByRole('button', { name: 'Annulla', exact: true }).click()
  await form.getByRole('button', { name: 'Elimina voce di Luca · Regalo', exact: true }).click()
  await checkBalance('+125,40 €')
  await person.fill('Test migliaia')
  await amount.fill('+110.000,00')
  await form.getByRole('button', { name: 'Aggiungi', exact: true }).click()
  await checkBalance('+110.125,40 €')
  await form.getByRole('button', { name: 'Copia saldo', exact: true }).click()
  if (await page.evaluate(() => navigator.clipboard.readText()) !== '+110125,40') throw new Error('Copy changed amount')
  await form.getByRole('button', { name: 'Elimina voce di Test migliaia', exact: true }).click()
  await checkBalance('+125,40 €')
  const labels = () => form.locator('.entry-description strong').allTextContents()
  const reorderHandle = form.getByRole('button', { name: 'Riordina Anna · Conguaglio', exact: true })
  await reorderHandle.focus()
  await reorderHandle.press('ArrowUp')
  await page.waitForFunction(() => document.querySelector('app-debt-credit .entry-description strong').textContent === 'Anna · Conguaglio')
  const start = await reorderHandle.boundingBox()
  const target = await form.getByRole('button', { name: 'Riordina Anna · Cena', exact: true }).boundingBox()
  await page.mouse.move(start.x + start.width / 2, start.y + start.height / 2)
  await page.mouse.down()
  await page.mouse.move(start.x + start.width / 2, start.y + start.height / 2 + 10, { steps: 4 })
  await page.mouse.move(target.x + target.width / 2, target.y + target.height, { steps: 15 })
  await page.mouse.up()
  await page.waitForFunction(() => document.querySelector('app-debt-credit .entry-description strong').textContent === 'Anna · Cena')
  // Tab changes retain the list and clear old copy feedback.
  await page.getByRole('button', { name: 'Calcolo', exact: true }).click()
  await page.getByRole('button', { name: 'Debiti/Crediti', exact: true }).click()
  await checkBalance('+125,40 €')
  await page.setViewportSize({ width: 390, height: 900 })
  const touchStart = await form.getByRole('button', { name: 'Riordina Anna · Conguaglio', exact: true }).boundingBox()
  const touchTarget = await form.getByRole('button', { name: 'Riordina Anna · Cena', exact: true }).boundingBox()
  const cdp = await page.context().newCDPSession(page)
  await cdp.send('Emulation.setTouchEmulationEnabled', { enabled: true })
  const touchX = touchStart.x + touchStart.width / 2
  const touchY = touchStart.y + touchStart.height / 2
  await cdp.send('Input.dispatchTouchEvent', { type: 'touchStart', touchPoints: [{ x: touchX, y: touchY }] })
  await new Promise(resolve => setTimeout(resolve, 220))
  for (let step = 1; step <= 12; step++) {
    await cdp.send('Input.dispatchTouchEvent', { type: 'touchMove', touchPoints: [{ x: touchX, y: touchY + (touchTarget.y - 10 - touchY) * step / 12 }] })
  }
  await cdp.send('Input.dispatchTouchEvent', { type: 'touchEnd', touchPoints: [] })
  await page.waitForFunction(() => document.querySelector('app-debt-credit .entry-description strong').textContent === 'Anna · Conguaglio')
  await cdp.send('Emulation.setTouchEmulationEnabled', { enabled: false })
  await cdp.detach()
  const expectedOrder = await labels()
  await page.setViewportSize({ width: 1280, height: 900 })
  // Real export download, then restore the exact JSON through the public file input.
  await page.getByRole('button', { name: 'Dati', exact: true }).click()
  await page.getByRole('button', { name: 'Esporta Dati', exact: true }).click()
  const downloadPromise = page.waitForEvent('download')
  await page.getByRole('button', { name: 'Esporta in JSON', exact: true }).click()
  const download = await downloadPromise
  await download.saveAs('output/playwright/debt-credit-backup.json')
  await page.getByRole('button', { name: 'Debiti/Crediti', exact: true }).click()
  await form.getByRole('button', { name: 'Elimina voce di Anna · Cena', exact: true }).click()
  await page.waitForFunction(() => document.querySelectorAll('app-debt-credit .entries li button[aria-label^="Elimina voce di Anna"]').length === 1)
  await form.getByRole('button', { name: 'Elimina voce di Anna · Conguaglio', exact: true }).click()
  await checkBalance('0,00 €')
  await page.getByRole('button', { name: 'Dati', exact: true }).click()
  await page.getByRole('button', { name: 'Importa con AI', exact: true }).click()
  // The CLI intercepts native dialogs; auto-confirm only this isolated guest restore.
  await page.evaluate(() => { window.confirm = () => true })
  await page.locator('input[type=file][accept=".json"]').setInputFiles('output/playwright/debt-credit-backup.json')
  await page.getByRole('button', { name: 'Debiti/Crediti', exact: true }).click()
  await checkBalance('+125,40 €')
  const sizes = []
  if (JSON.stringify(await labels()) !== JSON.stringify(expectedOrder)) throw new Error('Backup lost order')
  for (const width of [320, 390, 768, 1024, 1280]) {
    await page.setViewportSize({ width, height: 900 })
    sizes.push(await form.evaluate(el => ({ width: innerWidth, documentWidth: document.documentElement.scrollWidth, contentWidth: el.scrollWidth,
      rows: [...el.querySelectorAll('.entries li')].map(row => ({ height: row.getBoundingClientRect().height, actionText: row.querySelector('.entry-actions').textContent.trim() })) })))
  }
  if (sizes.some(s => s.documentWidth > s.width || s.contentWidth > s.width)) throw new Error('Responsive overflow: ' + JSON.stringify(sizes))
  if (sizes.some(s => s.rows.some(row => row.height > 60 || row.actionText))) throw new Error('Rows are not compact with icon-only actions: ' + JSON.stringify(sizes))
  await page.setViewportSize({ width: 390, height: 900 })
  await page.locator('app-header .lg\\:hidden button').first().click()
  await page.getByRole('button', { name: 'Calcolatore', exact: true }).click()
  await page.locator('app-calculator').waitFor()
  await page.locator('app-header .lg\\:hidden button').first().click()
  await page.getByRole('button', { name: 'Debiti/Crediti', exact: true }).click()
  await checkBalance('+125,40 €')
  await page.screenshot({ path: 'output/playwright/debt-credit-mobile.png' })
  await page.setViewportSize({ width: 1280, height: 900 })
  await page.screenshot({ path: 'output/playwright/debt-credit-desktop.png' })
  return { passed: 'explicit plus and grouped cents, unified field, mouse/keyboard/touch reorder, guest CRUD, clipboard, JSON export/restore, mobile navigation, responsive 320–1280px', sizes }
}
