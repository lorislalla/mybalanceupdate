// Local-only guest test. Never signs in or applies a remote migration.
async (page) => {
  page.setDefaultTimeout(6000)
  await page.setViewportSize({ width: 1280, height: 1000 })
  await page.goto('http://localhost:3001')
  await page.getByRole('button', { name: 'Entra come ospite (senza salvataggio dati)', exact: true }).click()
  const setMoney = async (label, text) => {
    const field = page.locator('app-money-field').filter({ has: page.getByText(label, { exact: true }) })
    await field.getByRole('button', { name: /^(Inserisci|Modifica) / }).click()
    const input = field.getByRole('textbox', { name: label, exact: true })
    await input.waitFor()
    await page.evaluate(() => new Promise(resolve => requestAnimationFrame(() => requestAnimationFrame(resolve))))
    await input.fill(text)
    await field.getByRole('button', { name: 'Salva', exact: true }).click()
    await input.waitFor({ state: 'detached' })
  }
  const checkLine = async (label, expected) => {
    const row = page.locator('.balance-line, .financial-total').filter({ has: page.getByText(label, { exact: true }) })
    await page.waitForFunction(({ label, expected }) => [...document.querySelectorAll('.balance-line, .financial-total')].some(row => row.querySelector('span')?.textContent === label && row.textContent.includes(expected)), { label, expected })
    if (!(await row.innerText()).includes(expected)) throw new Error(label + ' != ' + expected)
  }
  await setMoney('Liquidità al 1° del mese', '10.000,00')
  await setMoney('Investimenti al 1° del mese', '20.000,00')
  await setMoney('Versamenti netti del mese', '2.000,00')
  await setMoney('Stipendio 9/2026', '2000')
  await page.getByRole('combobox', { name: 'Spesa', exact: true }).fill('Spesa sintetica')
  await page.getByRole('textbox', { name: 'Importo · tua quota', exact: true }).fill('500')
  await page.getByRole('button', { name: 'Aggiungi spesa', exact: true }).click()
  await checkLine('Totale al 1° del mese', '30.000,00 €')
  await checkLine('Risparmio mensile', 'Non ancora disponibile')
  await page.getByRole('button', { name: 'Mese successivo', exact: true }).click()
  await setMoney('Liquidità al 1° del mese', '9500')
  await setMoney('Investimenti al 1° del mese', '22750')
  await page.getByRole('button', { name: 'Mese precedente', exact: true }).click()
  const expected = [['Totale a fine mese', '32.250,00 €'], ['Risparmio mensile', '1.500,00 €'], ['Risultato investimenti', '750,00 €'], ['Variazione totale', '2.250,00 €']]
  for (const [label, value] of expected) await checkLine(label, value)
  await setMoney('Versamenti netti del mese', '')
  await checkLine('Risparmio mensile', 'Non ancora disponibile')
  await checkLine('Risultato investimenti', 'Non ancora disponibile')
  await setMoney('Versamenti netti del mese', '0')
  await checkLine('Risparmio mensile', '-500,00 €')
  await checkLine('Risultato investimenti', '2.750,00 €')
  await setMoney('Versamenti netti del mese', '2000')
  await page.getByRole('button', { name: 'Mese successivo', exact: true }).click()
  await setMoney('Liquidità al 1° del mese', '0')
  await page.getByRole('button', { name: 'Mese precedente', exact: true }).click()
  await checkLine('Liquidità a fine mese', '0,00 €')
  await page.getByRole('button', { name: 'Mese successivo', exact: true }).click()
  await setMoney('Liquidità al 1° del mese', '9500')
  await setMoney('Investimenti al 1° del mese', '')
  await page.getByRole('button', { name: 'Mese precedente', exact: true }).click()
  await checkLine('Risultato investimenti', 'Non ancora disponibile')
  await checkLine('Risparmio mensile', '1.500,00 €')
  await page.getByRole('button', { name: 'Mese successivo', exact: true }).click()
  await setMoney('Investimenti al 1° del mese', '22750')
  await page.getByRole('button', { name: 'Mese precedente', exact: true }).click()
  await page.getByRole('button', { name: 'Dati', exact: true }).click()
  await page.getByRole('button', { name: 'Esporta Dati', exact: true }).click()
  const downloading = page.waitForEvent('download')
  await page.getByRole('button', { name: 'Esporta in JSON', exact: true }).click()
  const download = await downloading
  await download.saveAs('output/playwright/resoconto-investimenti-demo.json')
  let backupText = ''
  for await (const chunk of await download.createReadStream()) backupText += chunk.toString()
  const backup = JSON.parse(backupText)
  const october = backup.reports.find(report => report.month === 10)
  if (october.investmentValue !== 20000 || october.investmentNetFlow !== 2000 || october.balanceRecorded !== true) throw new Error('New fields missing in backup')
  await page.reload()
  await page.getByRole('button', { name: 'Entra come ospite (senza salvataggio dati)', exact: true }).click()
  await page.getByRole('button', { name: 'Dati', exact: true }).click()
  await page.evaluate(() => { window.confirm = () => true })
  await page.locator('input[type=file][accept=".json"]').setInputFiles('output/playwright/resoconto-investimenti-demo.json')
  await page.getByRole('button', { name: 'Resoconto', exact: true }).click()
  for (const [label, value] of expected) await checkLine(label, value)
  await page.getByRole('button', { name: 'Mese precedente', exact: true }).click()
  await page.getByRole('button', { name: 'Inserisci Saldo dopo stipendio', exact: true }).waitFor()
  if (await page.getByText('Investimenti al 1° del mese', { exact: true }).count()) throw new Error('Legacy months changed')
  await page.getByRole('button', { name: 'Mese successivo', exact: true }).click()
  const sizes = []
  for (const width of [320, 390, 768, 1280]) {
    await page.setViewportSize({ width, height: 1000 })
    sizes.push(await page.evaluate(() => ({ width: innerWidth, scroll: document.documentElement.scrollWidth })))
  }
  if (sizes.some(size => size.width !== size.scroll)) throw new Error('Horizontal overflow: ' + JSON.stringify(sizes))
  await page.locator('.balance-panel').screenshot({ path: 'output/playwright/resoconto-investimenti-desktop.png' })
  await page.setViewportSize({ width: 390, height: 1000 })
  await page.locator('.balance-panel').screenshot({ path: 'output/playwright/resoconto-investimenti-mobile.png' })
  // Simulate only the local auth state; no login and no network access are required.
  await page.evaluate(() => {
    const c = ng.getComponent(document.querySelector('app-monthly-report'))
    c.storageService.supabase.isGuestSession = false
    c.currentMonthYear.set('2026-11')
  })
  await page.getByRole('status').filter({ hasText: 'Anteprima locale' }).waitFor()
  const locked = await page.locator('.balance-section fieldset').evaluateAll(fields => fields.every(field => field.disabled))
  if (!locked) throw new Error('Authenticated preview editors are enabled before migration')
  return { passed: 'UI snapshots/flows, monthly separation, null/zero, next-month calculations, JSON roundtrip, legacy September, responsive, guest-only local guard', expected, sizes }
}
